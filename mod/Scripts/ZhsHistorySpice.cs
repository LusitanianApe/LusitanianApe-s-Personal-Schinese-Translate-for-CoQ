        private static readonly HashSet<string> _uncovered = new HashSet<string>();
        private static readonly object Gate = new object();
        private static string _logPath;
        private static int _written;
        private const int MaxEntries = 2000;

        public static void SetModDirectory(string dir)
        {
            if (string.IsNullOrEmpty(dir)) return;
            _logPath = Path.Combine(dir, "ZhsSpiceUncovered.log");
            // 自报家门：若这行没出现在 Player.log 里，说明引导到不了这里，
            // 那么"日志不生成"的原因就不在补丁，而在引导链。
            UnityEngine.Debug.Log("[QudZhsCookbook] 苏丹史词池：将对 " + Map.Count
                + " 条英文做整句替换；词池短语全集 " + Known.Count + " 条。未收录日志 -> " + _logPath);
        }

        /// <summary>
        /// ★ 2.15.69：这个展开结果**是否正好是词池里的一条短语**（= 中间单值，不是整句）。
        ///
        /// 【为什么需要】`HistoricStringExpander` 的**查询解析**方法（`ExpandQuery` 等）
        /// 返回的是「子类型解析出的单个值」（如 `astrologist`）。若把这种值译成中文，
        /// 它会被拼进后续查询 `spice.professions.占星家.guildhall` ⇒ 查表 miss
        /// ⇒ 生成器无限重试（实测 ×93,660 条 spice 引用失败）。
        /// ⇒ **只允许翻译最终整句**；命中本判据的一律放行原文。
        /// </summary>
        public static bool IsPoolPhrase(string s)
        {
            if (string.IsNullOrEmpty(s)) return false;
            return Known.Contains(s);
        }

        /// <summary>整句精确匹配；命中返回中文，未命中返回 null（调用方保留原文）。</summary>
        public static string Translate(string s)
        {
            if (string.IsNullOrEmpty(s)) return null;
            string v;
            return Map.TryGetValue(s, out v) ? v : null;
        }

        /// <summary>记录未收录的英文词池短语（去重、上限 2000 条），用于下一批补译。
        /// 只记确实来自 spice 词池的（Known 命中），否则日志会被无关英文占满。</summary>
        public static void NoteUncovered(string s)
        {
            try
            {
                if (_logPath == null || string.IsNullOrEmpty(s) || s.Length < 3) return;
                if (Markup.HasCjk(s)) return;
                if (!Known.Contains(s)) return;   // 不是词池短语 → 丢弃
                lock (Gate)
                {
                    if (_uncovered.Contains(s) || _written >= MaxEntries) return;
                    _uncovered.Add(s);
                    _written++;
                    File.AppendAllText(_logPath,
                        "[" + DateTime.Now.ToString("HH:mm:ss") + "] " + s + Environment.NewLine,
                        new UTF8Encoding(false));
                }
            }
            catch { }
        }
